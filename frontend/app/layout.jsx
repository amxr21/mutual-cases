import "./css/globals.css";
import localFont from "next/font/local"

import GlobalErrorListeners from './components/GlobalErrorListeners'
import { ToastProvider } from './components/Toast/ToastProvider'
import { LikeProvider } from './Context/LikeContext'
import { CartProvider } from './Context/CartContext'
import { I18nProvider } from './i18n/I18nProvider'
import Chrome from './components/Chrome'

const fraunces = localFont({
  src: '../public/fonts/FRAUNCES-REGULAR.woff2'
})

export const metadata = {
  title: "Mutual - Cases & more",
  description: "Generated by create next app",
};

// Applied before paint so language + direction are set with no flash.
// Arabic is disabled for now — force English/LTR and clear any stale saved choice
// so previous testers aren't stuck in RTL.
const themeScript = `(function(){try{
  localStorage.removeItem('mutual_lang');
  document.documentElement.setAttribute('lang', 'en');
  document.documentElement.setAttribute('dir', 'ltr');
}catch(e){}})();`

export default function RootLayout({ children }) {
  return (
    <html lang="en" dir="ltr" className={fraunces.className} suppressHydrationWarning>
      <head>
        <script dangerouslySetInnerHTML={{ __html: themeScript }} />
      </head>
      <body className={`font-default`}>
        <GlobalErrorListeners />
        <I18nProvider>
          <ToastProvider>
            <LikeProvider>
              <CartProvider>
                <Chrome>{children}</Chrome>
                <script
                  src="https://accounts.google.com/gsi/client"
                  strategy="afterInteractive"
                />
              </CartProvider>
            </LikeProvider>
          </ToastProvider>
        </I18nProvider>
      </body>
    </html>
  );
}
